<?php

namespace IPE\Dev\Markdown;

/**
 * @internal
 */
final class DynamicSection
{
    /**
     * @var \IPE\Dev\Markdown\GeneratedDocument
     */
    private $document;

    /**
     * @var non-empty-string
     */
    private $sectionIdentifier;

    /**
     * @var list<string> the lines before the "<!-- START OF <section> -->" line
     */
    private $beforeLines;

    /**
     * @var list<string>
     */
    private $sectionContentLines;

    /**
     * @var list<string> the lines after the "<!-- END OF <section> -->" line
     */
    private $afterLines;

    /**
     * @param non-empty-string $sectionIdentifier
     * @param list<string> $beforeLines
     * @param list<string> $sectionContentLines
     * @param list<string> $afterLines
     */
    private function __construct(GeneratedDocument $document, $sectionIdentifier, array $beforeLines, array $sectionContentLines, array $afterLines)
    {
        $this->document = $document;
        $this->sectionIdentifier = $sectionIdentifier;
        $this->beforeLines = $beforeLines;
        $this->sectionContentLines = $sectionContentLines;
        $this->afterLines = $afterLines;
    }

    /**
     * @param non-empty-string $sectionIdentifier
     * @param list<string> $documentLines
     *
     * @throws \RuntimeException if the section identifier is not valid, if only one of the placeholders exists, if they are repeated, or if they are in the wrong order
     *
     * @return self|null NULL if neither the start nor the end placeholder exists
     */
    public static function extractFrom(GeneratedDocument $document, $sectionIdentifier, array $documentLines)
    {
        if (!in_array($sectionIdentifier, $document->getSectionIdentifiers(), true)) {
            throw new \RuntimeException("Unrecognized section identifier of {$document->getFilename()}: {$sectionIdentifier}");
        }
        $startPlaceholder = self::getStartPlaceholder($sectionIdentifier);
        $endPlaceholder = self::getEndPlaceholder($sectionIdentifier);
        if (!in_array($startPlaceholder, $documentLines, true) && !in_array($endPlaceholder, $documentLines, true)) {
            return null;
        }
        $start = self::findSingleLine($document, $startPlaceholder, $documentLines);
        $end = self::findSingleLine($document, $endPlaceholder, $documentLines);
        if ($end < $start) {
            throw new \RuntimeException("The line {$endPlaceholder} comes before the line {$startPlaceholder} in {$document->getFilename()}");
        }
        $header = trim(self::getGeneratedContentHeader($document));
        $sectionContentLines = array_slice($documentLines, $start + 1, $end - $start - 1);
        $sectionContentLines = array_values(array_filter(
            $sectionContentLines,
            static function ($line) use ($header) {
                return strcasecmp(trim($line), $header) !== 0;
            }
        ));
        while (true) {
            $line = array_shift($sectionContentLines);
            if ($line === '') {
                continue;
            }
            if ($line !== null) {
                array_unshift($sectionContentLines, $line);
            }
            break;
        }
        while (true) {
            $line = array_pop($sectionContentLines);
            if ($line === '') {
                continue;
            }
            if ($line !== null) {
                $sectionContentLines[] = $line;
            }
            break;
        }

        return new self(
            $document,
            $sectionIdentifier,
            array_slice($documentLines, 0, $start),
            $sectionContentLines,
            array_slice($documentLines, $end + 1)
        );
    }

    /**
     * @return list<string>
     */
    public function getSectionContentLines()
    {
        return $this->sectionContentLines;
    }

    /**
     * @param list<string> $generatedLines
     *
     * @return self
     */
    public function withGeneratedContent(array $generatedLines)
    {
        return new self(
            $this->document,
            $this->sectionIdentifier,
            $this->beforeLines,
            $generatedLines,
            $this->afterLines
        );
    }

    /**
     * @return list<string>
     */
    public function getDocumentLines()
    {
        $header = self::getGeneratedContentHeader($this->document);

        return array_merge(
            $this->beforeLines,
            [
                self::getStartPlaceholder($this->sectionIdentifier),
                $header,
                '',
            ],
            $this->sectionContentLines,
            [
                '',
                $header,
                self::getEndPlaceholder($this->sectionIdentifier),
            ],
            $this->afterLines
        );
    }

    /**
     * @return non-empty-string
     */
    private static function getGeneratedContentHeader(GeneratedDocument $document)
    {
        return "<!-- Generated by {$document->getGenerator()}: do not edit -->";
    }

    /**
     * @param non-empty-string $sectionIdentifier
     *
     * @return non-empty-string
     */
    private static function getStartPlaceholder($sectionIdentifier)
    {
        return "<!-- START OF {$sectionIdentifier} -->";
    }

    /**
     * @param non-empty-string $sectionIdentifier
     *
     * @return non-empty-string
     */
    private static function getEndPlaceholder($sectionIdentifier)
    {
        return "<!-- END OF {$sectionIdentifier} -->";
    }

    /**
     * @param non-empty-string $line
     * @param list<string> $lines
     *
     * @throws \RuntimeException
     *
     * @return int
     */
    private static function findSingleLine(GeneratedDocument $document, $line, array $lines)
    {
        $indexes = array_keys($lines, $line, true);
        switch (count($indexes)) {
            case 0:
                throw new \RuntimeException("Unable to find the line {$line} in {$document->getFilename()}");
            case 1:
                return $indexes[0];
            default:
                throw new \RuntimeException("The line {$line} is repeated in {$document->getFilename()}");
        }
    }
}
