<?php

namespace IPE\Dev\Readme;

/**
 * @internal
 */
final class DynamicSection
{
    /**
     * @var non-empty-string
     * @public
     */
    const SECTION_SUPPORTED_EXTENSIONS = 'SUPPORTED PHP EXTENSIONS TABLE';

    /**
     * @var non-empty-string
     * @public
     */
    const SECTION_GENERAL_CLI_OPTIONS = 'GENERAL CLI OPTIONS';

    /**
     * @var non-empty-string
     * @public
     */
    const SECTION_EXTENSION_NOTES = 'EXTENSION NOTES';

    /**
     * @var non-empty-string
     * @public
     */
    const SECTION_SYSTEM_DEPENDENCY_OPTIONS = 'SYSTEM DEPENDENCY OPTIONS';

    /**
     * @var non-empty-string
     * @private
     */
    const GENERATED_CONTENT_HEADER = '<!-- Generated by scripts/update-readme.php: do not edit -->';

    /**
     * @var non-empty-string
     */
    private $sectionIdentifier;

    /**
     * @var list<string> the lines before the "<!-- START OF <section> -->" line
     */
    private $beforeLines;

    /**
     * @var list<string>
     */
    private $sectionContentLines;

    /**
     * @var list<string> the lines after the "<!-- END OF <section> -->" line
     */
    private $afterLines;

    /**
     * @param non-empty-string $sectionIdentifier
     * @param list<string> $beforeLines
     * @param list<string> $sectionContentLines
     * @param list<string> $afterLines
     */
    private function __construct($sectionIdentifier, array $beforeLines, array $sectionContentLines, array $afterLines)
    {
        $this->sectionIdentifier = $sectionIdentifier;
        $this->beforeLines = $beforeLines;
        $this->sectionContentLines = $sectionContentLines;
        $this->afterLines = $afterLines;
    }

    /**
     * @return list<non-empty-string>
     */
    public static function getSectionIdentifiers()
    {
        $class = new \ReflectionClass(self::class);
        $result = [];
        foreach ($class->getConstants() as $name => $value) {
            if (strpos($name, 'SECTION_') === 0 && is_string($value) && $value !== '') {
                $result[] = $value;
            }
        }

        return $result;
    }

    /**
     * @param non-empty-string $sectionIdentifier
     * @param list<string> $readmeLines
     *
     * @throws \RuntimeException if only one of the placeholders exists, if they are repeated, or if they are in the wrong order
     *
     * @return self|null NULL if neither the start nor the end placeholder exists
     */
    public static function extractFrom($sectionIdentifier, array $readmeLines)
    {
        if (!in_array($sectionIdentifier, self::getSectionIdentifiers(), true)) {
            throw new \RuntimeException("Unrecognized section identifier: {$sectionIdentifier}");
        }
        $startPlaceholder = self::getStartPlaceholder($sectionIdentifier);
        $endPlaceholder = self::getEndPlaceholder($sectionIdentifier);
        if (!in_array($startPlaceholder, $readmeLines, true) && !in_array($endPlaceholder, $readmeLines, true)) {
            return null;
        }
        $start = self::findSingleLine($startPlaceholder, $readmeLines);
        $end = self::findSingleLine($endPlaceholder, $readmeLines);
        if ($end < $start) {
            throw new \RuntimeException("The line {$endPlaceholder} comes before the line {$startPlaceholder} in README.md");
        }
        $sectionContentLines = array_slice($readmeLines, $start + 1, $end - $start - 1);
        $sectionContentLines = array_values(array_filter(
            $sectionContentLines,
            static function ($line) {
                return strcasecmp(trim($line), trim(self::GENERATED_CONTENT_HEADER)) !== 0;
            }
        ));
        while (true) {
            $line = array_shift($sectionContentLines);
            if ($line === '') {
                continue;
            }
            if ($line !== null) {
                array_unshift($sectionContentLines, $line);
            }
            break;
        }
        while (true) {
            $line = array_pop($sectionContentLines);
            if ($line === '') {
                continue;
            }
            if ($line !== null) {
                $sectionContentLines[] = $line;
            }
            break;
        }

        return new self(
            $sectionIdentifier,
            array_slice($readmeLines, 0, $start),
            $sectionContentLines,
            array_slice($readmeLines, $end + 1)
        );
    }

    /**
     * @return list<string>
     */
    public function getSectionContentLines()
    {
        return $this->sectionContentLines;
    }

    /**
     * @param list<string> $generatedLines
     *
     * @return self
     */
    public function withGeneratedContent(array $generatedLines)
    {
        return new self(
            $this->sectionIdentifier,
            $this->beforeLines,
            $generatedLines,
            $this->afterLines
        );
    }

    /**
     * @return list<string>
     */
    public function getReadmeLines()
    {
        return array_merge(
            $this->beforeLines,
            [
                self::getStartPlaceholder($this->sectionIdentifier),
                self::GENERATED_CONTENT_HEADER,
                '',
            ],
            $this->sectionContentLines,
            [
                '',
                self::GENERATED_CONTENT_HEADER,
                self::getEndPlaceholder($this->sectionIdentifier),
            ],
            $this->afterLines
        );
    }

    /**
     * @param non-empty-string $sectionIdentifier
     *
     * @return non-empty-string
     */
    private static function getStartPlaceholder($sectionIdentifier)
    {
        return "<!-- START OF {$sectionIdentifier} -->";
    }

    /**
     * @param non-empty-string $sectionIdentifier
     *
     * @return non-empty-string
     */
    private static function getEndPlaceholder($sectionIdentifier)
    {
        return "<!-- END OF {$sectionIdentifier} -->";
    }

    /**
     * @param non-empty-string $line
     * @param list<string> $lines
     *
     * @throws \RuntimeException
     *
     * @return int
     */
    private static function findSingleLine($line, array $lines)
    {
        $indexes = array_keys($lines, $line, true);
        switch (count($indexes)) {
            case 0:
                throw new \RuntimeException("Unable to find the line {$line} in README.md");
            case 1:
                return $indexes[0];
            default:
                throw new \RuntimeException("The line {$line} is repeated in README.md");
        }
    }
}
