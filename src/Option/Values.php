<?php

namespace IPE\Option;

/**
 * The values of the options of a resolved extension, after validation.
 */
final class Values
{
    /**
     * @var list<non-empty-string>
     */
    private $configureArguments;

    /**
     * @var array<string, string|true>
     */
    private $customValues;

    /**
     * @var list<non-empty-string>
     */
    private $defaultConfigureArguments;

    /**
     * @param list<non-empty-string> $configureArguments the arguments for ./configure (e.g. '--enable-foo', '--with-bar=/usr')
     * @param array<string, string|true> $customValues the values of the options handled by IPE (true for flags)
     * @param list<non-empty-string> $defaultConfigureArguments the arguments for the options not specified by the user: any other argument wins over them
     */
    public function __construct(array $configureArguments = [], array $customValues = [], array $defaultConfigureArguments = [])
    {
        $this->configureArguments = $configureArguments;
        $this->customValues = $customValues;
        $this->defaultConfigureArguments = $defaultConfigureArguments;
    }

    /**
     * @return list<non-empty-string> if an option is specified more than once, only the last occurrence is returned
     */
    public function getConfigureArguments()
    {
        $result = [];
        foreach (array_merge($this->defaultConfigureArguments, $this->configureArguments) as $index => $argument) {
            $key = self::getConfigureVariableKey($argument, $index);
            unset($result[$key]);
            $result[$key] = $argument;
        }

        return array_values($result);
    }

    /**
     * Get the key that identifies a configure argument: the options that configure scripts generated by autoconf store in the same variable have the same key.
     *
     * @param string $argument
     * @param int $index the value to be returned for the other arguments, which are never considered duplicated
     *
     * @return int|string
     */
    private static function getConfigureVariableKey($argument, $index)
    {
        $match = null;
        if (!preg_match('/^--(enable|disable|with|without)-([^=]+)/', $argument, $match)) {
            return $index;
        }

        return ($match[1] === 'enable' || $match[1] === 'disable' ? 'enable_' : 'with_') . strtr($match[2], '-+.', '___');
    }

    /**
     * @return array<string, string|true>
     */
    public function getCustomValues()
    {
        return $this->customValues;
    }

    /**
     * @param string $name
     *
     * @return bool
     */
    public function hasCustomValue($name)
    {
        return array_key_exists($name, $this->customValues);
    }

    /**
     * @param string $name
     * @param string|true|null $default
     *
     * @return string|true|null
     */
    public function getCustomValue($name, $default = null)
    {
        return array_key_exists($name, $this->customValues) ? $this->customValues[$name] : $default;
    }

    /**
     * Add configure arguments before the current ones specified by the user (so that the latter win if they conflict), but after the default ones.
     *
     * @param list<non-empty-string> $arguments
     *
     * @return self
     */
    public function withConfigureArgumentsBefore(array $arguments)
    {
        return new self(array_merge($arguments, $this->configureArguments), $this->customValues, $this->defaultConfigureArguments);
    }

    /**
     * @return bool
     */
    public function isEmpty()
    {
        return $this->configureArguments === [] && $this->defaultConfigureArguments === [] && $this->customValues === [];
    }
}
